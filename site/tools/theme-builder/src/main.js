import { THEME_GROUPS } from './theme-metadata.js';

/** @typedef {import('./theme-metadata.js').ThemeVariableDefinition} ThemeVariableDefinition */

/** Flat lookup for all public theme variables represented by the tool. */
const THEME_VARIABLES = new Map(
  THEME_GROUPS.flatMap((group) => group.variables.map((variable) => [variable.name, variable])),
);

/** User-authored values that differ textually from canonical defaults. */
const overrides = new Map();

/** Root that receives the live CSS custom-property overrides. */
const previewTracker = document.querySelector('[data-preview-tracker]');
/** Container for generated variable controls. */
const controlsRoot = document.querySelector('[data-controls]');
/** Live generated stylesheet preview. */
const cssOutput = document.querySelector('[data-css-output]');
/** Override count displayed above generated output. */
const modifiedCount = document.querySelector('[data-modified-count]');
/** Variable filter input. */
const variableFilter = document.querySelector('[data-variable-filter]');
/** Non-interruptive action feedback surface. */
const toast = document.querySelector('[data-toast]');
/** Orientation selector for the synthetic preview. */
const orientationControl = document.querySelector('[data-preview-control="orientation"]');
/** Placement selector for the synthetic preview. */
const placementControl = document.querySelector('[data-preview-control="placement"]');

if (
  !(previewTracker instanceof HTMLElement) ||
  !(controlsRoot instanceof HTMLElement) ||
  !(cssOutput instanceof HTMLElement) ||
  !(modifiedCount instanceof HTMLElement) ||
  !(variableFilter instanceof HTMLInputElement) ||
  !(toast instanceof HTMLElement) ||
  !(orientationControl instanceof HTMLSelectElement) ||
  !(placementControl instanceof HTMLSelectElement)
) {
  throw new Error('Theme Builder roots are missing.');
}

/** Toast dismissal timer shared across action feedback messages. */
let toastTimer = 0;

/**
 * Produces export CSS containing only explicit user overrides.
 *
 * @returns {string} Complete standalone override stylesheet.
 */
function buildExportCss() {
  const declarations = THEME_GROUPS.flatMap((group) => group.variables)
    .filter((definition) => overrides.has(definition.name))
    .map((definition) => `  ${definition.name}: ${overrides.get(definition.name)};`)
    .join('\n');
  const body = declarations === '' ? '  /* No overrides yet. */' : declarations;
  return `/* Generated by RXT Tracker Theme Builder */\n\n.rxtt {\n${body}\n}\n`;
}

/**
 * Shows short-lived UI feedback without blocking editing.
 *
 * @param {string} message Feedback text.
 * @returns {void}
 */
function showToast(message) {
  window.clearTimeout(toastTimer);
  toast.textContent = message;
  toast.dataset.visible = 'true';
  toastTimer = window.setTimeout(() => {
    delete toast.dataset.visible;
  }, 2200);
}

/**
 * Converts a browser-resolved opaque RGB color to a six-digit hex value.
 *
 * @param {string} value Candidate CSS color.
 * @returns {string | null} Hex color usable by input[type=color], or null when unsupported/transparent.
 */
function resolveColorToHex(value) {
  if (/\b(?:var|currentcolor|highlight)\b/iu.test(value) || !CSS.supports('color', value)) {
    return null;
  }

  const probe = document.createElement('span');
  probe.style.color = value;
  probe.style.position = 'absolute';
  probe.style.visibility = 'hidden';
  document.body.append(probe);
  const computedColor = getComputedStyle(probe).color;
  probe.remove();

  const channels = computedColor.match(/^rgba?\((\d+),?\s+(\d+),?\s+(\d+)(?:\s*\/\s*([\d.]+)|,\s*([\d.]+))?\)$/u);
  if (channels === null) {
    return null;
  }

  const alpha = channels[4] ?? channels[5];
  if (alpha !== undefined && Number(alpha) !== 1) {
    return null;
  }

  return `#${channels
    .slice(1, 4)
    .map((channel) => Number(channel).toString(16).padStart(2, '0'))
    .join('')}`;
}

/**
 * Validates one candidate in the CSS property context where Tracker consumes it.
 *
 * @param {ThemeVariableDefinition} definition Variable metadata.
 * @param {string} value Candidate value.
 * @returns {boolean} Whether the browser accepts the value for the mapped CSS property.
 */
function isValidValue(definition, value) {
  return value !== '' && CSS.supports(definition.cssProperty, value);
}

/**
 * Updates auxiliary editor state after the canonical text value changes.
 *
 * @param {HTMLElement} field Variable field root.
 * @param {ThemeVariableDefinition} definition Variable metadata.
 * @param {string} value Canonical current text value.
 * @returns {void}
 */
function syncAuxiliaryControl(field, definition, value) {
  const auxiliary = field.querySelector('[data-auxiliary]');
  if (auxiliary instanceof HTMLInputElement && auxiliary.type === 'color') {
    const hex = resolveColorToHex(value);
    auxiliary.disabled = hex === null;
    auxiliary.title = hex === null ? 'This CSS color cannot be represented by the native color picker.' : '';
    if (hex !== null) {
      auxiliary.value = hex;
    }
    return;
  }

  if (auxiliary instanceof HTMLInputElement && auxiliary.type === 'range') {
    const numericValue = Number(value);
    if (Number.isFinite(numericValue)) {
      auxiliary.value = String(numericValue);
    }
    return;
  }

  if (auxiliary instanceof HTMLSelectElement) {
    auxiliary.value = [...auxiliary.options].some((option) => option.value === value) ? value : '';
  }
}

/**
 * Applies one text value to validation, override state, preview, and generated output.
 *
 * @param {HTMLElement} field Variable field root.
 * @param {ThemeVariableDefinition} definition Variable metadata.
 * @param {string} value Candidate value from the canonical text editor.
 * @returns {void}
 */
function applyVariableValue(field, definition, value) {
  const valid = isValidValue(definition, value);
  field.dataset.invalid = String(!valid);

  const validation = field.querySelector('[data-validation]');
  if (validation instanceof HTMLElement) {
    validation.textContent = valid ? '' : `Invalid ${definition.cssProperty} value`;
  }

  if (!valid) {
    overrides.delete(definition.name);
    previewTracker.style.removeProperty(definition.name);
    delete field.dataset.modified;
    updateGeneratedOutput();
    return;
  }

  if (value === definition.defaultValue) {
    overrides.delete(definition.name);
    previewTracker.style.removeProperty(definition.name);
    delete field.dataset.modified;
  } else {
    overrides.set(definition.name, value);
    previewTracker.style.setProperty(definition.name, value);
    field.dataset.modified = 'true';
  }

  syncAuxiliaryControl(field, definition, value);
  updateGeneratedOutput();
}

/**
 * Restores one field to its canonical stylesheet fallback.
 *
 * @param {HTMLElement} field Variable field root.
 * @param {ThemeVariableDefinition} definition Variable metadata.
 * @returns {void}
 */
function resetVariable(field, definition) {
  const textInput = field.querySelector('[data-value-input]');
  if (!(textInput instanceof HTMLInputElement)) {
    return;
  }

  textInput.value = definition.defaultValue;
  delete field.dataset.invalid;
  delete field.dataset.modified;
  const validation = field.querySelector('[data-validation]');
  if (validation instanceof HTMLElement) {
    validation.textContent = '';
  }
  overrides.delete(definition.name);
  previewTracker.style.removeProperty(definition.name);
  syncAuxiliaryControl(field, definition, definition.defaultValue);
  updateGeneratedOutput();
}

/**
 * Creates the optional convenience editor paired with the canonical text input.
 *
 * @param {ThemeVariableDefinition} definition Variable metadata.
 * @returns {HTMLElement | null} Auxiliary input/select or null for text-only variables.
 */
function createAuxiliaryControl(definition) {
  if (definition.control === 'color') {
    const input = document.createElement('input');
    input.type = 'color';
    input.dataset.auxiliary = 'true';
    input.setAttribute('aria-label', `${definition.name} color picker`);
    return input;
  }

  if (definition.control === 'range') {
    const input = document.createElement('input');
    input.type = 'range';
    input.min = String(definition.min ?? 0);
    input.max = String(definition.max ?? 1);
    input.step = String(definition.step ?? 0.1);
    input.dataset.auxiliary = 'true';
    input.setAttribute('aria-label', `${definition.name} slider`);
    return input;
  }

  if (definition.control === 'select') {
    const select = document.createElement('select');
    select.dataset.auxiliary = 'true';
    select.setAttribute('aria-label', `${definition.name} suggested values`);
    const customOption = document.createElement('option');
    customOption.value = '';
    customOption.textContent = 'Custom';
    select.append(customOption);
    for (const value of definition.options ?? []) {
      const option = document.createElement('option');
      option.value = value;
      option.textContent = value;
      select.append(option);
    }
    return select;
  }

  return null;
}

/**
 * Creates a complete variable editor with metadata, validation, reset, and synchronized controls.
 *
 * @param {ThemeVariableDefinition} definition Variable metadata.
 * @returns {HTMLElement} Variable editor root.
 */
function createVariableField(definition) {
  const field = document.createElement('div');
  field.className = 'variable-field';
  field.dataset.variableName = definition.name;

  const header = document.createElement('div');
  header.className = 'variable-field__header';

  const name = document.createElement('code');
  name.className = 'variable-field__name';
  name.textContent = definition.name;

  const reset = document.createElement('button');
  reset.className = 'reset-button';
  reset.type = 'button';
  reset.textContent = 'Reset';
  reset.setAttribute('aria-label', `Reset ${definition.name}`);
  reset.addEventListener('click', () => resetVariable(field, definition));

  header.append(name, reset);

  const description = document.createElement('p');
  description.className = 'variable-field__description';
  description.textContent = definition.description;

  const editor = document.createElement('div');
  editor.className = 'variable-field__editor';

  const auxiliary = createAuxiliaryControl(definition);
  if (auxiliary !== null) {
    editor.append(auxiliary);
  }

  const textInput = document.createElement('input');
  textInput.className = 'value-input';
  textInput.type = 'text';
  textInput.value = definition.defaultValue;
  textInput.spellcheck = false;
  textInput.dataset.valueInput = 'true';
  textInput.setAttribute('aria-label', `${definition.name} CSS value`);
  editor.append(textInput);

  const footer = document.createElement('div');
  footer.className = 'variable-field__footer';

  const defaultValue = document.createElement('span');
  defaultValue.innerHTML = `Default: <code>${definition.defaultValue}</code>`;

  const validation = document.createElement('span');
  validation.className = 'variable-field__validation';
  validation.dataset.validation = 'true';
  validation.setAttribute('aria-live', 'polite');

  footer.append(defaultValue, validation);
  field.append(header, description, editor, footer);

  textInput.addEventListener('input', () => applyVariableValue(field, definition, textInput.value));

  if (auxiliary instanceof HTMLInputElement) {
    auxiliary.addEventListener('input', () => {
      textInput.value = auxiliary.value;
      applyVariableValue(field, definition, textInput.value);
    });
  } else if (auxiliary instanceof HTMLSelectElement) {
    auxiliary.addEventListener('change', () => {
      if (auxiliary.value === '') {
        textInput.focus();
        return;
      }
      textInput.value = auxiliary.value;
      applyVariableValue(field, definition, textInput.value);
    });
  }

  syncAuxiliaryControl(field, definition, definition.defaultValue);
  return field;
}

/**
 * Renders all public theme groups and their controls from the metadata registry.
 *
 * @returns {void}
 */
function renderControls() {
  const fragment = document.createDocumentFragment();

  for (const group of THEME_GROUPS) {
    const details = document.createElement('details');
    details.className = 'control-group';
    details.dataset.group = group.id;
    details.open = group.id !== 'advanced';

    const summary = document.createElement('summary');
    const summaryCopy = document.createElement('span');
    summaryCopy.innerHTML = `<strong>${group.title}</strong><small>${group.description}</small>`;
    const count = document.createElement('span');
    count.className = 'control-group__count';
    count.textContent = String(group.variables.length);
    summary.append(summaryCopy, count);

    const body = document.createElement('div');
    body.className = 'control-group__body';
    for (const variable of group.variables) {
      body.append(createVariableField(variable));
    }

    details.append(summary, body);
    fragment.append(details);
  }

  controlsRoot.replaceChildren(fragment);
}

/**
 * Refreshes generated stylesheet text and the explicit override count.
 *
 * @returns {void}
 */
function updateGeneratedOutput() {
  cssOutput.textContent = buildExportCss();
  const count = overrides.size;
  modifiedCount.textContent = `${count} ${count === 1 ? 'override' : 'overrides'}`;
}

/**
 * Resets all public variables while preserving preview-only layout state.
 *
 * @returns {void}
 */
function resetAllVariables() {
  for (const [name, definition] of THEME_VARIABLES) {
    const field = controlsRoot.querySelector(`[data-variable-name="${name}"]`);
    if (field instanceof HTMLElement) {
      resetVariable(field, definition);
    }
  }
  showToast('All theme overrides reset.');
}

/**
 * Copies generated CSS using the modern Clipboard API.
 *
 * @returns {Promise<void>} Resolves after success or user-visible failure handling.
 */
async function copyGeneratedCss() {
  if (!navigator.clipboard) {
    showToast('Clipboard API is unavailable in this context.');
    return;
  }

  try {
    await navigator.clipboard.writeText(buildExportCss());
    showToast('CSS copied to clipboard.');
  } catch {
    showToast('Clipboard permission was denied.');
  }
}

/**
 * Downloads generated overrides as a standalone CSS file.
 *
 * @returns {void}
 */
function exportGeneratedCss() {
  const blob = new Blob([buildExportCss()], { type: 'text/css;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = 'rxt-tracker-theme.css';
  link.click();
  URL.revokeObjectURL(url);
  showToast('tracker-theme.css exported.');
}

/**
 * Filters variable fields by custom-property name, description, or group title.
 *
 * @param {string} query Search query.
 * @returns {void}
 */
function filterVariables(query) {
  const normalizedQuery = query.trim().toLowerCase();
  for (const group of controlsRoot.querySelectorAll('.control-group')) {
    if (!(group instanceof HTMLDetailsElement)) {
      continue;
    }

    const fields = [...group.querySelectorAll('.variable-field')];
    let visibleCount = 0;
    for (const field of fields) {
      if (!(field instanceof HTMLElement)) {
        continue;
      }
      const text = field.textContent?.toLowerCase() ?? '';
      const matches = normalizedQuery === '' || text.includes(normalizedQuery);
      field.hidden = !matches;
      visibleCount += Number(matches);
    }

    group.hidden = visibleCount === 0;
    if (normalizedQuery !== '' && visibleCount > 0) {
      group.open = true;
    }
  }
}

/**
 * Synchronizes placement options with the selected preview orientation.
 *
 * @returns {void}
 */
function updatePreviewLayout() {
  const orientation = orientationControl.value;
  const placementOptions = orientation === 'vertical' ? ['right', 'left'] : ['bottom', 'top'];
  const previousPlacement = placementControl.value;

  placementControl.replaceChildren(
    ...placementOptions.map((value) => {
      const option = document.createElement('option');
      option.value = value;
      option.textContent = value[0].toUpperCase() + value.slice(1);
      return option;
    }),
  );

  placementControl.value = placementOptions.includes(previousPlacement) ? previousPlacement : placementOptions[0];
  previewTracker.dataset.rxttOrientation = orientation;
  previewTracker.dataset.rxttPlacement = placementControl.value;
}

/**
 * Routes document-level Theme Builder actions.
 *
 * @param {MouseEvent} event Click event.
 * @returns {void}
 */
function handleAction(event) {
  const target = event.target;
  if (!(target instanceof Element)) {
    return;
  }

  const actionButton = target.closest('[data-action]');
  if (!(actionButton instanceof HTMLButtonElement)) {
    return;
  }

  switch (actionButton.dataset.action) {
    case 'reset-all':
      resetAllVariables();
      break;
    case 'copy':
      void copyGeneratedCss();
      break;
    case 'export':
      exportGeneratedCss();
      break;
    case 'focus-preview':
      previewTracker.focus();
      break;
    default:
      break;
  }
}

renderControls();
updateGeneratedOutput();
updatePreviewLayout();

document.addEventListener('click', handleAction);
variableFilter.addEventListener('input', () => filterVariables(variableFilter.value));
orientationControl.addEventListener('change', updatePreviewLayout);
placementControl.addEventListener('change', () => {
  previewTracker.dataset.rxttPlacement = placementControl.value;
});
